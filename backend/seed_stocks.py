def fetch_from_eastmoney(industry_code, industry_name):
    """尝试从东财拉取行业股票列表"""
    url = "https://push2.eastmoney.com/api/qt/clist/get"
    params = (f"pn=1&pz=500&po=0&np=1&fltt=2&invt=2"
              f"&fs=b:{industry_code}+f:!200&fields=f12,f14")
    full_url = f"{url}?{params}"
    req_obj = urllib.request.Request(full_url)
    req_obj.add_header("User-Agent", UA)
    try:
        resp = urllib.request.urlopen(req_obj, timeout=15)
        data = json.loads(resp.read().decode("utf-8"))
        items = data.get("data", {}).get("diff", [])
        codes = []
        for item in items:
            code = item.get("f12", "")
            name = item.get("f14", "")
            if code and not (code.startswith("200") or code.startswith("900") or code.startswith("300000")):
                codes.append({"code": code, "name": name})
        if codes:
            return codes
    except:
        pass
    return None

def fetch_name(code):
    """从腾讯财经获取股票名称"""
    prefix = f"sh{code}" if code.startswith(("6", "9")) else f"sz{code}"
    url = f"https://qt.gtimg.cn/q={prefix}"
    try:
        resp = urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=8)
        vals = resp.read().decode("gbk").split('"')[1].split("~")
        return vals[1] if len(vals) > 1 else code
    except:
        return code


